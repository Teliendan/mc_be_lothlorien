"""Wildlife wariness table (LM-01): one native flight goal per animal, judged per player by the player's Harmony band tag.

    python -B mods/lothlorien/tools/wildlife_wariness.py --matrix             # the table, band x sneak x held item
    python -B mods/lothlorien/tools/wildlife_wariness.py --write deer white_deer swan squirrel
    python -B mods/lothlorien/tools/wildlife_wariness.py --check              # entity files agree with the table

Every wildlife animal (deer, white deer, swan, squirrel, unicorn) carries a `minecraft:behavior.avoid_mob_type` whose player
entries read the player's runtime band tag (scripts/harmony.js BAND_TAGS; Guest = none of the four). Distances and speeds are
the one table below; `--write` replaces only the avoid and tempt blocks of the groups `lothlorien:state_wild`,
`lothlorien:state_tame` (deer, white deer) and `lothlorien:state_alarmed` in the hand-written entity files. The unicorn file is
generated by make_unicorn.py, which imports `wild_avoid` and `tempt` from here (`--check` still compares it).

Rules the entries keep (verified in game unless noted, see skill bedrock-mobs references/behaviour.md):
- flat tests only inside an entry (`has_tag`/`has_equipment` with `!=` where a negation is needed; no nested none_of);
- exactly one player entry matches a player per band x sneak x held item, or none when the lure exempts the holder;
- a positive `has_tag` test inside avoid_mob_type is NOT yet confirmed in game (only `!=` is);
- the lure exemption (`has_equipment !=` the lure) exists only for Friend and Guest (unicorn: Friend only). A lure holder of a
  worse band is fled from at the sneak distance and approaches again while sneaking: owner accepted come-and-flee (2026-11-11).
"""
import argparse
import json
import sys
from pathlib import Path

from json_io import write_json

MOD = Path(__file__).resolve().parents[1]
ENTITIES = MOD / "lothlorien_bp" / "entities"

# Runtime player tag per band; Guest has none. Equal to scripts/harmony.js BAND_TAGS (tests/wildlife_wariness_check.py).
BAND_TAGS = {"friend": "lothlorien_friend", "uneasy": "lothlorien_uneasy", "shunned": "lothlorien_shunned", "hated": "lothlorien_hated"}
BANDS = ["friend", "guest", "uneasy", "shunned", "hated"]

# band -> (walking distance, sneaking distance, walk speed multiplier, sprint speed multiplier), in blocks
FLIGHT = {
    "friend": (3, 2, 1.1, 1.3),
    "guest": (10, 5, 1.3, 1.6),
    "uneasy": (13, 6, 1.4, 1.7),
    "shunned": (20, 10, 1.5, 1.9),
    "hated": (30, 15, 1.6, 2.1),
}
UNICORN_GUEST = (13, 6, 1.4, 1.7)  # a stranger is as timid as an Uneasy player
ALARMED = (36, 18, 1.6, 2.1)  # every player, no exemption
DANGER = [
    {"filters": {"test": "is_family", "subject": "other", "value": "wolf"}, "max_dist": 12, "walk_speed_multiplier": 1.4, "sprint_speed_multiplier": 1.8},
    {"filters": {"test": "is_family", "subject": "other", "value": "monster"}, "max_dist": 8, "walk_speed_multiplier": 1.4, "sprint_speed_multiplier": 1.8},
]
AVOID_PRIORITY = 3  # above tempt: a wolf or an unwelcome player beats the lure
TEMPT_PRIORITY = 4
TEMPT_RADIUS = 10  # explicit (the engine default is not recorded); the unicorn's lure always had 10

CORN = "lothlorien:western_corn_grain"
ACORN = "lothlorien:mallorn_acorn"
WHEAT = "minecraft:wheat"
ELANOR = "lothlorien:elanor"

# species -> lure items (held item = no flight for Friend and Guest, and the tempt goal's items), whether it has a tame group
SPECIES = {
    "deer": {"lures": [CORN], "tame": True},
    "white_deer": {"lures": [ACORN], "tame": True},
    "swan": {"lures": [WHEAT, CORN], "tame": False},
    "squirrel": {"lures": [ACORN], "tame": False},
    "unicorn": {"lures": [ELANOR], "tame": False},
}
HAND_WRITTEN = ["deer", "white_deer", "swan", "squirrel"]  # `--write` targets; make_unicorn.py generates the unicorn


def flight(species, band):
    return UNICORN_GUEST if species == "unicorn" and band == "guest" else FLIGHT[band]


def exempt_bands(species):
    """Bands whose lure holder is not fled from (the lure must reach the animal)."""
    return ("friend",) if species == "unicorn" else ("friend", "guest")


def band_tests(band):
    if band == "guest":  # no band tag at all
        return [{"test": "has_tag", "subject": "other", "operator": "!=", "value": tag} for tag in BAND_TAGS.values()]
    return [{"test": "has_tag", "subject": "other", "value": BAND_TAGS[band]}]


def player_entry(band, sneaking, dist, walk, sprint, lures):
    tests = [{"test": "is_family", "subject": "other", "value": "player"}, {"test": "is_sneaking", "subject": "other", "value": sneaking}]
    if band is not None:
        tests += band_tests(band)
    tests += [{"test": "has_equipment", "subject": "other", "domain": "hand", "operator": "!=", "value": item} for item in lures]
    return {"filters": {"all_of": tests}, "max_dist": dist, "walk_speed_multiplier": walk, "sprint_speed_multiplier": sprint}


def band_entries(species, bands):
    lures = SPECIES[species]["lures"]
    entries = []
    for band in bands:
        walking, sneaking, walk, sprint = flight(species, band)
        exempt = lures if band in exempt_bands(species) else []
        entries += [player_entry(band, False, walking, walk, sprint, exempt), player_entry(band, True, sneaking, walk, sprint, exempt)]
    return entries


def avoid(entries):
    return {"priority": AVOID_PRIORITY, "entity_types": entries + json.loads(json.dumps(DANGER))}


def wild_avoid(species):
    """The wild animal's flight goal: every band judged by its own tag."""
    return avoid(band_entries(species, BANDS))


def tame_avoid(species):
    """A tame deer is not fled from by Guest and Friend, only by Uneasy or worse (and the danger entries)."""
    return avoid(band_entries(species, ["uneasy", "shunned", "hated"]))


def alarmed_avoid():
    walking, sneaking, walk, sprint = ALARMED
    return avoid([player_entry(None, False, walking, walk, sprint, []), player_entry(None, True, sneaking, walk, sprint, [])])


def tempt(species):
    return {"priority": TEMPT_PRIORITY, "speed_multiplier": 1.0, "items": list(SPECIES[species]["lures"]),
            "within_radius": TEMPT_RADIUS, "can_get_scared": False}


AVOID, TEMPT = "minecraft:behavior.avoid_mob_type", "minecraft:behavior.tempt"


def expected_groups(species):
    """group name -> {component: value} for the blocks this tool owns in the entity file (the unicorn's tempt lives in `lure`)."""
    groups = {"lothlorien:state_alarmed": {AVOID: alarmed_avoid()}}
    if species == "unicorn":
        groups["lothlorien:state_wild"] = {AVOID: wild_avoid(species)}
        groups["lothlorien:lure"] = {TEMPT: tempt(species)}
    else:
        groups["lothlorien:state_wild"] = {AVOID: wild_avoid(species), TEMPT: tempt(species)}
        if SPECIES[species]["tame"]:
            groups["lothlorien:state_tame"] = {AVOID: tame_avoid(species), TEMPT: tempt(species)}
    return groups


def write_species(species):
    path = ENTITIES / f"{species}.json"
    data = json.loads(path.read_text(encoding="utf-8"))
    groups = data["minecraft:entity"]["component_groups"]
    fresh = {}  # groups the file does not have yet go first (state_wild, state_tame); existing ones keep their place
    for name, blocks in expected_groups(species).items():
        if name in groups:
            groups[name].update(blocks)
        else:
            fresh[name] = dict(blocks)
    data["minecraft:entity"]["component_groups"] = {**fresh, **groups}
    write_json(path, data)


def check_species(species):
    """Returns a list of problems; empty when the file's owned blocks equal the table (or the file is not migrated yet)."""
    data = json.loads((ENTITIES / f"{species}.json").read_text(encoding="utf-8"))["minecraft:entity"]["component_groups"]
    if "lothlorien:state_wild" not in data:
        return None
    problems = []
    for name, blocks in expected_groups(species).items():
        for component, value in blocks.items():
            if data.get(name, {}).get(component) != value:
                problems.append(f"{species}.json {name} {component} differs from the table")
    return problems


def matrix():
    lines = []
    for species in SPECIES:
        lures = SPECIES[species]["lures"]
        lines.append(f"{species} (lure: {', '.join(lures)})")
        lines.append("  band     walk/sneak  speed(walk/sprint)  lure holder")
        for band in BANDS:
            walking, sneaking, walk, sprint = flight(species, band)
            holder = "not fled" if band in exempt_bands(species) else f"fled at {sneaking} sneaking, {walking} walking (come-and-flee)"
            lines.append(f"  {band:<8} {walking:>3}/{sneaking:<3}     {walk}/{sprint}           {holder}")
        walking, sneaking, walk, sprint = ALARMED
        lines.append(f"  alarmed  {walking:>3}/{sneaking:<3}     {walk}/{sprint}           fled (all players)")
    return "\n".join(lines)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--matrix", action="store_true", help="print the table")
    parser.add_argument("--write", nargs="+", metavar="SPECIES", choices=HAND_WRITTEN, help="rewrite the avoid/tempt blocks in these entity files")
    parser.add_argument("--check", action="store_true", help="fail when an entity file differs from the table")
    args = parser.parse_args(argv)
    if args.matrix:
        print(matrix())
    for species in args.write or []:
        write_species(species)
        print(f"wrote {species}.json")
    if args.check:
        failed = 0
        for species in SPECIES:
            problems = check_species(species)
            if problems is None:
                print(f"skip {species}: no lothlorien:state_wild group yet")
            elif problems:
                failed += 1
                print("\n".join(f"FAIL {p}" for p in problems))
            else:
                print(f"ok   {species}")
        return 1 if failed else 0
    return 0


if __name__ == "__main__":
    sys.exit(main())
